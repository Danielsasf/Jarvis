const { contextBridge, ipcRenderer } = require('electron');

const call = async (channel, ...args) => {
  try {
    return await ipcRenderer.invoke(channel, ...args);
  } catch (err) {
    throw new Error(String(err?.message || err).replace(/^Error invoking remote method '[^']+': (Error: )?/, ''));
  }
};
const on = (channel) => (fn) => ipcRenderer.on(channel, (_e, payload) => fn(payload));

contextBridge.exposeInMainWorld('jarvis', {
  getState: () => call('state:get'),
  addAccount: (data) => call('account:add', data),
  disconnect: (id) => call('provider:disconnect', id),
  updateProvider: (id, patch) => call('provider:update', id, patch),
  runComputer: (action) => call('computer:run', action),
  setComputer: (patch) => call('computer:set', patch),
  addComputerApp: () => call('computer:addApp'),
  removeComputerApp: (id) => call('computer:removeApp', id),
  unpause: (id) => call('provider:unpause', id),
  setOrder: (order) => call('order:set', order),
  setSettings: (patch) => call('settings:set', patch),
  detectLocal: () => call('local:detect'),
  send: (reqId, messages) => call('chat:send', reqId, messages),
  stop: (reqId) => call('chat:stop', reqId),
  transcribe: (audio, mime) => call('stt:transcribe', audio, mime),
  openExternal: (url) => call('open:external', url),
  checkUpdate: () => call('update:check'),
  installUpdate: () => call('update:install'),
  togglePack: (id, on) => call('packs:toggle', id, on),
  savePack: (data) => call('packs:save', data),
  importPack: () => call('packs:import'),
  deletePack: (id) => call('packs:delete', id),
  openPackFolder: () => call('packs:folder'),
  packPdf: (id) => call('packs:pdf', id),
  getNews: () => call('news:get'),
  setNews: (on) => call('news:set', on),
  exportPack: (id) => call('packs:export', id),
  addMemory: (text) => call('memory:add', text),
  removeMemory: (id) => call('memory:remove', id),
  clearMemory: () => call('memory:clear'),
  getChats: () => call('chats:all'),
  saveChat: (chat) => call('chats:save', chat),
  deleteChat: (id) => call('chats:delete', id),
  exportChat: (chat) => call('chats:export', chat),
  setNotify: (patch) => call('notify:set', patch),
  testNotify: () => call('notify:test'),
  morningNotify: () => call('notify:morning'),
  setGcal: (patch) => call('gcal:set', patch),
  connectGcal: () => call('gcal:connect'),
  disconnectGcal: () => call('gcal:disconnect'),
  confirmEvent: (id) => call('cal:confirm', id),
  dismissEvent: (id) => call('cal:dismiss', id),
  setCal: (patch) => call('cal:set', patch),
  testCal: () => call('cal:test'),
  setMail: (patch) => call('mail:set', patch),
  testMail: () => call('mail:test'),
  setRemote: (patch) => call('remote:set', patch),
  remoteCode: () => call('remote:code'),
  revokeDevice: (id) => call('remote:revoke', id),
  recheckRemote: () => call('remote:recheck'),
  onRemoteChat: on('chats:remote'),
  getWake: () => call('wake:get'),
  getStats: () => call('sys:stats'),
  getSysDetail: () => call('sys:detail'),
  getWeather: () => call('weather:get'),
  setWeather: (city) => call('weather:set', city),
  onWake: on('wake:event'),
  onLog: on('jarvis:log'),
  onState: on('jarvis:state'),
  onDelta: on('chat:delta'),
  onStatus: on('chat:status'),
  onUpdate: on('update:status'),
});
